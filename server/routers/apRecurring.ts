/**
 * apRecurring.ts — P1-d Recurring auto-pay (Melio-inspired AP suite)
 *
 * Router: apRecurringRouter
 *  - createSchedule  — idempotent (withIdempotency, REQUIRED key min 8);
 *      computes the first next_run_at from startAt + frequency.
 *  - listSchedules / getSchedule — merchant-scoped reads.
 *  - updateSchedule — guarded UPDATE ... WHERE id AND merchantId RETURNING;
 *      only is_active, max_amount_kobo, auto_approve_below_kobo, next_run_at
 *      are mutable (template/frequency are immutable after creation).
 *  - cancelSchedule — guarded is_active flip (active → inactive).
 *  - runHistory — bills generated by a schedule
 *      (ap_bills.source_ref LIKE 'recurring:{scheduleId}:%').
 *  - triggerNow — idempotent manual run of ONE schedule through the SAME
 *      core executor the cron sweep uses (executeRecurringScheduleRun in
 *      server/cronJobs.ts): claim-first (guarded run_count increment +
 *      next_run_at advance), then generate the bill.
 *
 * Conventions (IMPLEMENTATION_SPEC_MELIO.md §D1–D8, §P1-d):
 *  - merchant identity ALWAYS resolved server-side from ctx.user.openId
 *    (crud119.ts:110 resolveMerchantId pattern) — never from client input
 *  - money as bigint kobo; withIdempotency on create/trigger mutations
 *  - Kafka paygate.ap.bills (non-fatal) + auditLog() after mutations
 *  - The schedule executor itself lives in server/cronJobs.ts
 *    (processRecurringBillSchedules) and inserts ap_bills rows directly via
 *    drizzle — it does NOT import apBillPay (no cross-router coupling).
 */

